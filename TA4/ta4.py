# RBR

# rule 1 : coffee reccomendation
def rule_coffee(product, preferences):
  if (preferences["wants_coffee"] and product["category"] == "coffee"):
    return True

  return False

# rule 2 : pastry recommendation
def rule_pastry(product, preferences):
  if (preferences["wants_pastry"] and product["category"] == "pastry"):
    return True

  return False

# rule 3 : pasta recommendation
def rule_pasta(product, preferences):
  if (preferences["wants_pasta"] and product["category"] == "pasta"):
    return True

  return False

# inference
def inference_engine(menu, preferences):

  recommendations = []

  # check menu
  for product_name, details in menu.items():

    # ignore unavail prods
    if not details["availability"]:
      continue

    # check all rules
    if rule_coffee(details, preferences):
      recommendations.append(product_name)

    elif rule_pastry(details, preferences):
      recommendations.append(product_name)

    elif rule_pasta(details, preferences):
      recommendations.append(product_name)

  return recommendations


# retrieve most similar previous case

def retrieve_case(case_base, new_problem):

    most_similar_case = None
    highest_score = -1

    for case in case_base:

        matching_features = 0

        for feature in new_problem:

            if case["problem"][feature] == new_problem[feature]:
                matching_features += 1

        similarity = matching_features / len(new_problem)

        if similarity > highest_score:
            highest_score = similarity
            most_similar_case = case

    return most_similar_case, highest_score


# reuse solution from the retrieved case

def reuse_solution(retrieved_case):

    if retrieved_case is None:
        return []

    return retrieved_case["solution"].copy()

# revise solutions by modifying reccoss

def revise_solution(solution, menu):

    print("\nCurrent Recommendation:", ", ".join(solution))

    choice = input("Would you like to revise this recommendation? (y/n): ").lower()

    if choice == "y":

        print("\nAvailable Products:")

        for product in menu:
            if menu[product]["availability"]:
                print("-", product)

        new_items = input(
            "\nEnter your preferred products separated by commas: "
        )

        revised_solution = [
            item.strip() for item in new_items.split(",")
            if item.strip() in menu and menu[item.strip()]["availability"]
        ]

        if revised_solution:
            return revised_solution

        print("No valid products entered. Keeping original recommendation.")

    return solution

# retain or store the new case for future recommendations

def retain_case(case_base, problem, solution):

    new_case = {
        "problem": problem.copy(),
        "solution": solution.copy()
    }

    case_base.append(new_case)

    print("\nNew case successfully added to the case base!")



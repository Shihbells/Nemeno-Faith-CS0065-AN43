import nltk

# Download the public dataset
nltk.download('opinion_lexicon')

from nltk.corpus import opinion_lexicon

# Get the happy and sad words
happy_words = set(opinion_lexicon.positive())
sad_words = set(opinion_lexicon.negative())


def number_happy(sentence):
    words = sentence.lower().split()
    count = 0

    for word in words:
        word = word.strip(".,!?;:\"'()[]{}")
        if word in happy_words:
            count += 1

    return count


def number_sad(sentence):
    words = sentence.lower().split()
    count = 0

    for word in words:
        word = word.strip(".,!?;:\"'()[]{}")
        if word in sad_words:
            count += 1

    return count


# Main program
sentence = input("Enter a sentence: ")

happy = number_happy(sentence)
sad = number_sad(sentence)

print("\nNumber of happy words:", happy)
print("Number of sad words:", sad)

if happy > sad:
    print("The tone of the sentence is positive.")
elif sad > happy:
    print("The tone of the sentence is negative.")
else:
    print("The tone of the sentence is neutral.")
class Environment:
    """Class representing the two-room environment."""
    def __init__(self, room_a_state: str, room_b_state: str):
        # Store state in a dictionary as required by Task 1
        self.rooms = {
            'A': room_a_state.capitalize(),
            'B': room_b_state.capitalize()
        }

    def is_dirty(self, room: str) -> bool:
        """Check if a given room is dirty."""
        return self.rooms.get(room) == "Dirty"

    def clean_room(self, room: str) -> None:
        """Clean a given room."""
        self.rooms[room] = "Clean"


class RuleBasedAgent:
    """Class representing the Rule-Based Vacuum Cleaner Agent."""
    def __init__(self, start_location: str):
        self.current_location = start_location

    def perceive_and_act(self, env: Environment) -> str:
        """Perceive current state and decide on an action based on rules."""
        # Rule 1: If current room is dirty, clean it
        if env.is_dirty(self.current_location):
            env.clean_room(self.current_location)
            return f"{self.current_location} has been cleaned"

        # Rule 2: If current room is clean, move to the other room
        else:
            self.move()
            return f"Moving to Room {self.current_location}"

    def move(self) -> None:
        """Switch agent location between Room A and Room B."""
        if self.current_location == 'A':
            self.current_location = 'B'
        else:
            self.current_location = 'A'


def main():
    print("=== Rule-Based Vacuum Cleaner Simulation ===")

    # Task 1: Initialize Environment from User Input
    state_a = input("Enter status for Room A (Clean/Dirty): ").strip()
    state_b = input("Enter status for Room B (Clean/Dirty): ").strip()
    start_loc = input("Enter starting room for Agent (A/B): ").strip().upper()

    env = Environment(state_a, state_b)
    agent = RuleBasedAgent(start_loc)

    # Task 3: Input step count and run simulation
    steps = int(input("\nHow many steps should the agent run: "))

    for step in range(1, steps + 1):
        print(f"\nStep {step}:")
        print(f"  Agent Location : Room {agent.current_location}")

        # Execute perceive-and-act cycle
        action = agent.perceive_and_act(env)

        print(f"  Room {action}")
        print(f"  Environment State: {env.rooms}")


if __name__ == "__main__":
    main()
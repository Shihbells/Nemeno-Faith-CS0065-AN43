class Environment:
    """Class representing the three-room environment."""
    def __init__(self, room_a: str, room_b: str, room_c: str):
        self.rooms = {
            'A': room_a.capitalize(),
            'B': room_b.capitalize(),
            'C': room_c.capitalize()
        }

    def is_dirty(self, room: str) -> bool:
        """Check if a room is dirty."""
        return self.rooms.get(room) == "Dirty"

    def clean_room(self, room: str) -> None:
        """Clean a room."""
        self.rooms[room] = "Clean"

    def all_clean(self) -> bool:
        """Check if all rooms in the environment are clean."""
        return all(status == "Clean" for status in self.rooms.values())


class RuleBasedAgent:
    """Class representing the Rule-Based Vacuum Cleaner Agent."""
    def __init__(self, start_location: str = 'A'):
        self.current_location = start_location

    def perceive_and_act(self, env: Environment) -> str:
        """Decide action based on rules."""
        # Check if all rooms are clean
        if env.all_clean():
            return "All rooms are clean. Agent is idle."

        # Rule 1: If current room is dirty, clean it
        if env.is_dirty(self.current_location):
            env.clean_room(self.current_location)
            return f"Room {self.current_location} has been cleaned."

        # Rule 2: If current room is clean, move to the next room
        else:
            self.move()
            return f"Moving to room {self.current_location}"

    def move(self) -> None:
        """Cycle agent through rooms A -> B -> C -> A."""
        if self.current_location == 'A':
            self.current_location = 'B'
        elif self.current_location == 'B':
            self.current_location = 'C'
        else:
            self.current_location = 'A'


def display_grid(env: Environment, agent: RuleBasedAgent) -> str:
    """For [A-Clean] [B-Agent] [C-Dirty]."""
    grid_items = []
    for room in ['A', 'B', 'C']:
        if agent.current_location == room:
            grid_items.append(f"[{room}-Agent]")
        else:
            grid_items.append(f"[{room}-{env.rooms[room]}]")
    return " ".join(grid_items)


def main():
    # for room statuses
    state_a = "Clean"
    state_b = input("Is room B Dirty or Clean? ").strip()
    state_c = input("Is room C Dirty or Clean? ").strip()

    env = Environment(state_a, state_b, state_c)
    agent = RuleBasedAgent(start_location='A')

    steps = int(input("\nHow many steps should the agent run? "))

    for step in range(1, steps + 1):
        print(f"\nStep {step}:")

        # Display state BEFORE action
        print(display_grid(env, agent))

        # Agent perceives environment and decides action
        action_msg = agent.perceive_and_act(env)
        print(action_msg)

        # Display state AFTER action
        print(display_grid(env, agent))


if __name__ == "__main__":
    main()